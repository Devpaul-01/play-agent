-- SQLite schema for play-agent.
--
-- Two tables per architecture doc Sec13: `runs` and `attempts`. This schema
-- is dual-purpose -- it's both the audit trail for a single run and the raw
-- data source the evaluation harness (Sec17) reads from later. No separate
-- eval-logging system is planned; don't add one without updating Sec13.

PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS runs (
    id              TEXT PRIMARY KEY,       -- UUID4, generated by the orchestrator
    test_identifier TEXT NOT NULL,          -- e.g. path + test title, stable across runs
    repo_commit_ref TEXT,                   -- commit SHA of the app-under-test at run time, if known
    created_at      TEXT NOT NULL,          -- ISO 8601 UTC
    updated_at      TEXT NOT NULL,          -- ISO 8601 UTC, bumped on every state transition

    -- Final state once the run concludes; NULL while still in progress.
    -- Mirrors the state machine's terminal states (Sec6).
    final_state     TEXT CHECK (
                        final_state IS NULL OR final_state IN (
                            'succeeded', 'failed', 'rejected', 'cancelled'
                        )
                    ),
    rejection_reason TEXT                   -- populated when final_state = 'rejected' or 'failed'
);

CREATE TABLE IF NOT EXISTS attempts (
    id                  INTEGER PRIMARY KEY AUTOINCREMENT,
    run_id              TEXT NOT NULL REFERENCES runs(id) ON DELETE CASCADE,

    candidate_rank      INTEGER NOT NULL,   -- 1, 2, ... ; distinguishes candidate attempts
                                             -- from a re-diagnosis pass (see attempt_kind)
    attempt_kind        TEXT NOT NULL CHECK (
                            attempt_kind IN ('candidate', 're_diagnosis')
                        ),

    diagnosis_reasoning TEXT,               -- model's stated reasoning for this candidate
    patch_locator_call_id       TEXT,       -- the {locatorCallId, ...} patch representation (Sec9)
    patch_new_locator_expr      TEXT,       -- the newLocatorExpression half of the same patch

    verification_outcome TEXT CHECK (
                            verification_outcome IS NULL OR verification_outcome IN (
                                'pass', 'fail', 'flaky'
                            )
                        ),
    verification_reps   INTEGER,            -- N repeated runs used for the flake-check (Sec7)

    token_usage_prompt     INTEGER,
    token_usage_completion INTEGER,
    estimated_cost_usd     REAL,

    state_entered_at    TEXT NOT NULL,      -- ISO 8601 UTC
    state_duration_ms   INTEGER             -- populated once the attempt concludes
);

CREATE INDEX IF NOT EXISTS idx_attempts_run_id ON attempts(run_id);
CREATE INDEX IF NOT EXISTS idx_runs_test_identifier ON runs(test_identifier);